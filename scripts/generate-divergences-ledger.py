#!/usr/bin/env python3
"""Assemble the divergence ledger from its per-owner sources.

The ledger entries live with their owner: one TOML file per check (or
per run topic) in ``crates/rpmcrab-core/data/divergences/``, named the
way ``crates/rpmcrab-core/data/descriptions/`` names its per-check
files. This script assembles the sources into
``tests/parity/divergences.toml`` — owner files in name order, entries
in file order within an owner — and stamps the output as generated.

The checked-in aggregate is what the parity tooling reads (the parity
runner, the ledger schema tests in
``crates/rpmcrab-core/tests/divergences_ledger.rs`` and
``divergences_missing.rs``, and ``scripts/audit-reference-coverage.py``);
the sources are what a change edits. This script runs by hand and in CI
(the ``divergences-ledger-drift`` job), never at build time, and the
runtime never reads the sources.

Usage:
    scripts/generate-divergences-ledger.py [--check]

    --check      regenerate in memory and diff against the committed
                 aggregate; exit 1 with a unified diff on any
                 divergence.
"""

import argparse
import difflib
import os
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC_DIR = REPO / "crates/rpmcrab-core/data/divergences"
LEDGER = REPO / "tests/parity/divergences.toml"

STAMP = (
    "# Generated by scripts/generate-divergences-ledger.py from the\n"
    "# per-owner sources in crates/rpmcrab-core/data/divergences/ — edit\n"
    "# the sources there and re-run the generator. The parity tooling\n"
    "# reads this aggregate.\n"
)

HEADER_RE = re.compile(r"(?m)^\[\[divergence\]\]")

REFERENCE_CHECKS = REPO / "crates/rpmcrab-core/tests/data/reference-checks.txt"

# Run topics: entries keyed by a topic of the run rather than by a
# check (the session header, the report shape, the config layer, ...).
# An owner file is named for one of these or for a check from the
# reference set (REFERENCE_CHECKS).
RUN_TOPICS = frozenset({
    "after_checks",
    "all",
    "argument-globbing",
    "build-env-severity-cap",
    "check-error-handling",
    "cli",
    "config",
    "config-scoring",
    "config-severity-overrides",
    "finding-line",
    "header-decoding",
    "installed-pkg-layer",
    "interrupt-handling",
    "pkg-layer",
    "report",
    "rpmlintrc-discovery",
    "rpmlintrc-uses-setbadness",
    "session-header",
    "time-report",
    "unused-rpmlintrc-filter",
    "worker-report",
})


def known_owners():
    """The owner names a source file may use: every check in the
    reference set plus the run topics."""
    checks = {line.strip() for line in
              REFERENCE_CHECKS.read_text(encoding="utf-8").splitlines()
              if line.strip() and not line.startswith("#")}
    return checks | RUN_TOPICS


def extract_blocks(text):
    """The `[[divergence]]` blocks of a source file, verbatim.

    Everything before the first header (the file's comment header) is
    skipped; a block runs to the next header or end of file, with
    trailing blank lines stripped.
    """
    starts = [m.start() for m in HEADER_RE.finditer(text)]
    blocks = []
    for i, s in enumerate(starts):
        e = starts[i + 1] if i + 1 < len(starts) else len(text)
        blocks.append(text[s:e].rstrip("\n"))
    return blocks


def assemble(src_dir, owners=None):
    """The aggregate ledger text built from the sources in `src_dir`.

    Every source parses as TOML and contributes exactly as many
    `[[divergence]]` entries as it carries blocks — a source whose
    blocks and entries disagree (a fused entry, a second table style)
    fails loudly here instead of drifting the aggregate. A source's
    only top-level table is `divergence`, per source and per block:
    a stray key or table (a dropped first header, an interleaved
    `[other]` table) fails loudly instead of losing an entry or
    smuggling one into the aggregate. With `owners` given, every
    source's owner is one of them — a registered check or a listed
    run topic.
    """
    blocks = []
    for name in sorted(os.listdir(src_dir)):
        if not name.endswith(".toml"):
            continue
        if owners is not None and Path(name).stem not in owners:
            raise ValueError(
                f"{name}: the owner is not a registered check or a "
                "listed run topic")
        text = (Path(src_dir) / name).read_text(encoding="utf-8")
        parsed = tomllib.loads(text)
        if set(parsed) != {"divergence"}:
            raise ValueError(
                f"{name}: top-level keys are {sorted(parsed)}, not "
                "just 'divergence' — a source carries only "
                "[[divergence]] blocks")
        entries = parsed.get("divergence", [])
        file_blocks = extract_blocks(text)
        if len(entries) != len(file_blocks):
            raise ValueError(
                f"{name}: {len(file_blocks)} [[divergence]] blocks but "
                f"{len(entries)} parsed entries — entries are written as "
                "[[divergence]] blocks, one entry per block")
        for block in file_blocks:
            one = tomllib.loads(block + "\n")
            if set(one) != {"divergence"}:
                raise ValueError(
                    f"{name}: a block carries top-level keys "
                    f"{sorted(one)}, not just 'divergence'")
            if len(one.get("divergence", [])) != 1:
                raise ValueError(f"{name}: a block does not parse to "
                                 "exactly one entry")
            blocks.append(block)
    return STAMP + "\n" + "\n\n".join(blocks) + "\n", len(blocks)


def generate():
    return assemble(SRC_DIR, owners=known_owners())


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Assemble tests/parity/divergences.toml from the "
                    "per-owner sources in "
                    "crates/rpmcrab-core/data/divergences/.")
    parser.add_argument("--check", action="store_true",
                        help="diff the committed aggregate against a "
                             "fresh assembly; exit 1 on divergence")
    args = parser.parse_args(argv)

    text, count = generate()
    if args.check:
        current = LEDGER.read_text(encoding="utf-8")
        if current == text:
            print(f"divergences ledger is current ({count} entries)")
            return 0
        print("drift: tests/parity/divergences.toml", file=sys.stderr)
        diff = difflib.unified_diff(
            current.splitlines(keepends=True),
            text.splitlines(keepends=True),
            fromfile="tests/parity/divergences.toml (committed)",
            tofile="tests/parity/divergences.toml (generated)")
        sys.stderr.writelines(diff)
        return 1
    LEDGER.write_text(text, encoding="utf-8")
    print(f"wrote tests/parity/divergences.toml ({count} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
